// +,-,*,/,%

let a = 10;
let b = 5;

// Arithmetic Operators
let sum = a + b; // addition
let sub = a - b; // subtraction
let mul = a * b; // multiplication
let div = a / b; // division
let mod = a % b; // modulus

console.log(sum);
console.log(sub);
console.log(mul);
console.log(div);
console.log(mod);

// n%2 == 1 - odd number, [n%2 == 0 - even number]
// Exponential Operator ** , power 2^3 ->8
console.log(2 ** 3); // 8
console.log(a ** b); // 100000
